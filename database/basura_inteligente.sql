CREATE DATABASE IF NOT EXISTS basura_inteligente CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE basura_inteligente;

SET FOREIGN_KEY_CHECKS = 0;
DROP TABLE IF EXISTS alertas;
DROP TABLE IF EXISTS lecturas_sensor;
DROP TABLE IF EXISTS detalle_ruta;
DROP TABLE IF EXISTS rutas;
DROP TABLE IF EXISTS reportes_ciudadanos;
DROP TABLE IF EXISTS usuarios;
DROP TABLE IF EXISTS contenedores;
DROP TABLE IF EXISTS camiones;
SET FOREIGN_KEY_CHECKS = 1;

-- -------------------------------------------------------------
-- Camiones recolectores
-- -------------------------------------------------------------
CREATE TABLE camiones (
    id INT AUTO_INCREMENT PRIMARY KEY,
    codigo VARCHAR(20) NULL,
    placa VARCHAR(20) NOT NULL UNIQUE,
    conductor VARCHAR(100) NOT NULL,
    telefono_conductor VARCHAR(20) NULL,
    licencia VARCHAR(30) NULL,
    categoria_licencia VARCHAR(5) NULL,
    vencimiento_licencia DATE NULL,
    capacidad VARCHAR(30) NOT NULL,
    tipo_residuo VARCHAR(30) NOT NULL,
    estado VARCHAR(30) NOT NULL DEFAULT 'Activo',
    fecha_registro DATETIME DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- -------------------------------------------------------------
-- Usuarios del sistema (contraseñas cifradas con password_hash)
-- -------------------------------------------------------------
CREATE TABLE usuarios (
    id INT AUTO_INCREMENT PRIMARY KEY,
    nombre VARCHAR(100) NOT NULL,
    usuario VARCHAR(50) NOT NULL UNIQUE,
    password VARCHAR(255) NOT NULL,
    rol VARCHAR(20) NOT NULL DEFAULT 'recolector',
    id_camion INT NULL,
    estado VARCHAR(20) NOT NULL DEFAULT 'Activo',
    fecha_registro DATETIME DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_usuario_camion FOREIGN KEY (id_camion) REFERENCES camiones(id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- -------------------------------------------------------------
-- Contenedores de residuos (con datos del sensor IoT)
-- -------------------------------------------------------------
CREATE TABLE contenedores (
    id INT AUTO_INCREMENT PRIMARY KEY,
    codigo VARCHAR(30) NOT NULL UNIQUE,
    ubicacion VARCHAR(150) NOT NULL,
    zona VARCHAR(10) NOT NULL,
    capacidad VARCHAR(30) NOT NULL,
    estado VARCHAR(30) NOT NULL DEFAULT 'Activo',
    tipo_residuo VARCHAR(30) NOT NULL,
    nivel_llenado INT NOT NULL DEFAULT 0,
    latitud DECIMAL(10,7) NULL,
    longitud DECIMAL(10,7) NULL,
    codigo_sensor VARCHAR(30) NULL,
    bateria INT NULL,
    ultima_lectura DATETIME NULL,
    fecha_registro DATETIME DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- -------------------------------------------------------------
-- Rutas de recolección y su detalle (orden de los contenedores)
-- -------------------------------------------------------------
CREATE TABLE rutas (
    id INT AUTO_INCREMENT PRIMARY KEY,
    nombre_ruta VARCHAR(100) NOT NULL,
    id_camion INT NULL,
    tipo_residuo VARCHAR(30) NOT NULL,
    fecha DATE NOT NULL,
    hora TIME NOT NULL,
    estado VARCHAR(30) NOT NULL DEFAULT 'Pendiente',
    lat_inicio DECIMAL(10,7) NULL,
    lng_inicio DECIMAL(10,7) NULL,
    lat_fin DECIMAL(10,7) NULL,
    lng_fin DECIMAL(10,7) NULL,
    distancia DECIMAL(8,2) NULL,
    tiempo_estimado VARCHAR(20) NULL,
    fecha_registro DATETIME DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_ruta_camion FOREIGN KEY (id_camion) REFERENCES camiones(id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE detalle_ruta (
    id INT AUTO_INCREMENT PRIMARY KEY,
    id_ruta INT NOT NULL,
    id_contenedor INT NOT NULL,
    orden INT NOT NULL,
    recolectado TINYINT(1) NOT NULL DEFAULT 0,
    hora_recoleccion DATETIME NULL,
    CONSTRAINT fk_detalle_ruta FOREIGN KEY (id_ruta) REFERENCES rutas(id) ON DELETE CASCADE,
    CONSTRAINT fk_detalle_contenedor FOREIGN KEY (id_contenedor) REFERENCES contenedores(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- -------------------------------------------------------------
-- Lecturas enviadas por los sensores IoT
-- -------------------------------------------------------------
CREATE TABLE lecturas_sensor (
    id INT AUTO_INCREMENT PRIMARY KEY,
    id_contenedor INT NOT NULL,
    nivel INT NOT NULL,
    bateria INT NULL,
    fecha DATETIME DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_lectura_contenedor FOREIGN KEY (id_contenedor) REFERENCES contenedores(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- -------------------------------------------------------------
-- Alertas generadas automáticamente
-- -------------------------------------------------------------
CREATE TABLE alertas (
    id INT AUTO_INCREMENT PRIMARY KEY,
    id_contenedor INT NOT NULL,
    tipo VARCHAR(50) NOT NULL,
    mensaje VARCHAR(255) NOT NULL,
    estado VARCHAR(20) NOT NULL DEFAULT 'Pendiente',
    fecha DATETIME DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_alerta_contenedor FOREIGN KEY (id_contenedor) REFERENCES contenedores(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- -------------------------------------------------------------
-- Reportes enviados por la ciudadanía
-- -------------------------------------------------------------
CREATE TABLE reportes_ciudadanos (
    id INT AUTO_INCREMENT PRIMARY KEY,
    nombre VARCHAR(100) NOT NULL,
    telefono VARCHAR(20) NULL,
    tipo_problema VARCHAR(60) NOT NULL,
    descripcion TEXT NOT NULL,
    ubicacion VARCHAR(150) NOT NULL,
    latitud DECIMAL(10,7) NULL,
    longitud DECIMAL(10,7) NULL,
    estado VARCHAR(20) NOT NULL DEFAULT 'Pendiente',
    fecha DATETIME DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE INDEX idx_contenedor_tipo ON contenedores(tipo_residuo, estado);
CREATE INDEX idx_lectura_fecha ON lecturas_sensor(id_contenedor, fecha);


